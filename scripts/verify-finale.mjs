import assert from 'node:assert/strict';
import { build } from 'esbuild';

const bundled = await build({ stdin: { contents: `export * from './src/finale/JourneySigilConfig.ts'; export * from './src/finale/RestorationState.ts'; export * from './src/game/GameState.ts'; export * from './src/portals/echo/EchoPuzzleState.ts'; export * from './src/world/worldCosmetics.ts';`, resolveDir: process.cwd(), loader: 'ts' }, bundle: true, platform: 'node', format: 'esm', write: false });
const api = await import(`data:text/javascript;base64,${Buffer.from(bundled.outputFiles[0].contents).toString('base64')}`);
const a = api.journeySigilForSeed('SLICE_0379');
const b = api.journeySigilForSeed('SLICE_0380');
assert.deepEqual(a, api.journeySigilForSeed('SLICE_0379'));
assert.deepEqual(b, api.journeySigilForSeed('SLICE_0380'));
assert.deepEqual([a.id, a.shape, a.lightFacet, a.echoOffset, a.balanceBars, a.celestialPoints], ['B230', 'spire', 0, 0, 1, 3]);
assert.deepEqual([b.id, b.shape, b.lightFacet, b.echoOffset, b.balanceBars, b.celestialPoints], ['D7EE', 'spire', 2, 4, 3, 4]);
assert.notDeepEqual(a, b);
const snapshot = seed => {
  const game = api.createInitialGameState(seed);
  return { light: game.light, echo: game.echo.sequences, balance: game.balance.layout, celestial: game.celestial, world: api.createWorldCosmetics(seed, 42) };
};
const before = snapshot('SLICE_0379');
api.journeySigilForSeed('SLICE_0379');
assert.deepEqual(snapshot('SLICE_0379'), before, 'Finale seed forks changed portal or island generation');
assert.notDeepEqual(snapshot('SLICE_0380'), before, 'Known second journey must meaningfully differ');
assert.equal(api.restorationStage(0), 'awakening');
assert.equal(api.restorationStage(1.01), 'light');
assert.equal(api.restorationStage(2.41), 'echo');
assert.equal(api.restorationStage(3.81), 'balance');
assert.equal(api.restorationStage(5.21), 'celestial');
assert.equal(api.restorationStage(6.71), 'sockets');
assert.equal(api.restorationStage(8.11), 'monument');
assert.equal(api.restorationStage(9.71), 'sigil');
assert.equal(api.restorationStage(12.11), 'restored');
let game = api.createInitialGameState('SLICE_0379');
assert.equal(api.activateRestoration(game, 1000), game, 'Incomplete journey activated the monument');
game = { ...game, completedPortals: [1, 2, 3, 4] };
const playing = api.activateRestoration(game, 1000);
assert.equal(playing.restoration.phase, 'playing');
assert.equal(playing.restoration.startedAt, 1000);
assert.equal(api.activateRestoration(playing, 2000), playing, 'Rapid repeat activation restarted the finale');
assert.equal(api.enterPortal(playing, 1), playing, 'Portal travel interrupted the finale');
const complete = api.completeRestoration(playing);
assert.equal(complete.restoration.phase, 'complete');
assert.equal(api.completeRestoration(complete), complete, 'Completion replayed');
assert.deepEqual(api.restoreGameState(api.gameProgress(complete)).restoration, complete.restoration);
const fresh = api.startNewJourney(complete, 'SLICE_0380');
assert.equal(fresh.restoration.phase, 'dormant');
assert.equal(fresh.scene, 'ISLAND');
assert.deepEqual(fresh.completedPortals, []);
assert.deepEqual([1, 2, 3, 4].map(portal => api.portalStatus(fresh, portal)), ['active', 'locked', 'locked', 'locked']);
assert.notEqual(api.journeySigilForSeed(fresh.runSeed).id, a.id);
const generated = api.startNewJourney(complete);
assert.notEqual(generated.runSeed, complete.runSeed);
assert.notEqual(generated.light.variant, complete.light.variant);
assert.notEqual(api.journeySigilForSeed(generated.runSeed).id, a.id);
console.log(`Finale seed snapshots: SLICE_0379 → ${a.id} ${a.shape}; SLICE_0380 → ${b.id} ${b.shape}. Stages, duplicate prevention, portal isolation and New Journey verified.`);
