export function CelestialGlyph({ symbol, color, scale = 1, opacity = 1 }: { symbol: CelestialSymbol; color: string; scale?: number; opacity?: number }) {
  return <group scale={scale}>{glyphs[symbol].flatMap((path, pathIndex) => path.slice(1).map((point, index) => {
    const from = path[index], dx = point[0] - from[0], dy = point[1] - from[1];
    return <mesh key={`${pathIndex}-${index}`} position={[(from[0] + point[0]) / 2, (from[1] + point[1]) / 2, 0]} rotation={[0, 0, Math.atan2(dy, dx)]}>
      <boxGeometry args={[Math.hypot(dx, dy), 0.065, 0.035]} />
      <meshBasicMaterial color={color} transparent opacity={opacity} depthWrite={false} />
    </mesh>;
  }))}</group>;
}
